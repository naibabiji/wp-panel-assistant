// Generates brand assets from assets/brand/logo-2048.png using Electron's nativeImage
// (no extra image tools needed). Run from the repository root:
//   tabby/node_modules/.bin/electron tools/generate-brand-assets.cjs
// Outputs:
//   tabby/build/windows/icon.ico                 Windows app/installer icon (PNG-compressed ICO, 16-256 px)
//   tabby/tabby-wp-panel/src/brand/logo.ts       256 px logo as a data URL for the plugin UI
//   tabby/app/assets/wppa-logo.png               256 px logo for the startup screen (app/src/preload.scss)
const { app, nativeImage } = require('electron')
const fs = require('fs')
const path = require('path')

const root = path.resolve(__dirname, '..')
const src = path.join(root, 'assets/brand/logo-2048.png')

function buildIco (pngs) {
    const header = Buffer.alloc(6)
    header.writeUInt16LE(0, 0) // reserved
    header.writeUInt16LE(1, 2) // type: icon
    header.writeUInt16LE(pngs.length, 4)
    const entries = []
    let offset = 6 + 16 * pngs.length
    for (const { size, data } of pngs) {
        const e = Buffer.alloc(16)
        e.writeUInt8(size >= 256 ? 0 : size, 0) // width (0 = 256)
        e.writeUInt8(size >= 256 ? 0 : size, 1) // height
        e.writeUInt8(0, 2) // palette
        e.writeUInt8(0, 3) // reserved
        e.writeUInt16LE(1, 4) // color planes
        e.writeUInt16LE(32, 6) // bits per pixel
        e.writeUInt32LE(data.length, 8)
        e.writeUInt32LE(offset, 12)
        offset += data.length
        entries.push(e)
    }
    return Buffer.concat([header, ...entries, ...pngs.map(p => p.data)])
}

app.whenReady().then(() => {
    const img = nativeImage.createFromPath(src)
    if (img.isEmpty()) { throw new Error('cannot read ' + src) }
    const { width, height } = img.getSize()
    const bmp = img.toBitmap() // BGRA
    const cornerAlpha = bmp[3]
    console.log(`source ${width}x${height}, top-left alpha=${cornerAlpha}`)

    const sizes = [16, 24, 32, 48, 64, 128, 256]
    const pngs = sizes.map(size => ({ size, data: img.resize({ width: size, height: size, quality: 'best' }).toPNG() }))
    const ico = path.join(root, 'tabby/build/windows/icon.ico')
    fs.writeFileSync(ico, buildIco(pngs))
    console.log('wrote', ico, fs.statSync(ico).size, 'bytes')

    const logo256 = pngs.find(p => p.size === 256).data.toString('base64')
    const ts = path.join(root, 'tabby/tabby-wp-panel/src/brand/logo.ts')
    fs.mkdirSync(path.dirname(ts), { recursive: true })
    fs.writeFileSync(ts, `// Generated by tools/generate-brand-assets.cjs from assets/brand/logo-2048.png - do not edit.\nexport const LOGO_DATA_URL = 'data:image/png;base64,${logo256}'\n`)
    console.log('wrote', ts, fs.statSync(ts).size, 'bytes')
    const splash = path.join(root, 'tabby/app/assets/wppa-logo.png')
    fs.writeFileSync(splash, pngs.find(p => p.size === 256).data)
    console.log('wrote', splash, fs.statSync(splash).size, 'bytes')
    app.quit()
}).catch(e => { console.error(e); app.exit(1) })
